/** Normalized title key used to match admitted Depository rows to catalog packs. */
export function demonstrationDataPackTitleKey(title: string | null | undefined): string {
  return String(title || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

/** Resolve a catalog pack by its title or commercial title (normalized). */
export function findDemonstrationDataPackByTitle(
  title: string | null | undefined,
): DemonstrationDataPack | null {
  const key = demonstrationDataPackTitleKey(title);
  if (!key) return null;
  return (
    DEMONSTRATION_DATA_PACK_CATALOG.find(
      (pack) =>
        demonstrationDataPackTitleKey(pack.title) === key ||
        demonstrationDataPackTitleKey(pack.commercialTitle) === key,
    ) ?? null
  );
}
