CREATE OR REPLACE FUNCTION "pg_temp"."v49_rename_jsonb"("value" jsonb) RETURNS jsonb
LANGUAGE plpgsql AS $$
DECLARE
  "text_value" text;
  "pair" record;
BEGIN
  IF "value" IS NULL THEN
    RETURN NULL;
  END IF;
  "text_value" := "value"::text;
  FOR "pair" IN SELECT "old_token", "new_token" FROM "v49_evaluations_token_map" ORDER BY length("old_token") DESC LOOP
    "text_value" := replace("text_value", '"' || "pair"."old_token" || '"', '"' || "pair"."new_token" || '"');
  END LOOP;
  RETURN "text_value"::jsonb;
END;
$$;

CREATE OR REPLACE FUNCTION "pg_temp"."v49_rename_text"("value" text) RETURNS text
LANGUAGE sql AS $$
  SELECT coalesce((SELECT "new_token" FROM "v49_evaluations_token_map" WHERE "old_token" = "value"), "value");
$$;

